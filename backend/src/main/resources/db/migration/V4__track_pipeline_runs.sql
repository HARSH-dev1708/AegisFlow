ALTER TABLE pipelines
    ADD COLUMN duration_seconds BIGINT;

UPDATE pipelines
SET started_at = created_at,
    finished_at = CASE
        WHEN UPPER(status) IN ('SUCCESS', 'FAILED', 'CANCELLED') THEN updated_at
        ELSE NULL
    END,
    duration_seconds = NULL;

CREATE TABLE pipeline_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pipeline_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    level VARCHAR(20) NOT NULL,
    message VARCHAR(4000) NOT NULL,
    CONSTRAINT fk_pipeline_logs_pipeline FOREIGN KEY (pipeline_id) REFERENCES pipelines (id)
);

CREATE INDEX idx_pipeline_logs_pipeline_created
    ON pipeline_logs (pipeline_id, created_at, id);

CREATE INDEX idx_pipelines_status_created
    ON pipelines (status, created_at);
