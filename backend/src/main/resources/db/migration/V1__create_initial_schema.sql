CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles (id)
);

CREATE TABLE refresh_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_refresh_sessions_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE environments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255)
);

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    repository_url VARCHAR(255),
    status VARCHAR(30) NOT NULL,
    environment_id BIGINT NOT NULL,
    owner_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_projects_environment FOREIGN KEY (environment_id) REFERENCES environments (id),
    CONSTRAINT fk_projects_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);

CREATE TABLE pipelines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    branch VARCHAR(100) NOT NULL,
    commit_hash VARCHAR(50),
    status VARCHAR(30) NOT NULL,
    project_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_pipelines_project FOREIGN KEY (project_id) REFERENCES projects (id)
);

CREATE TABLE pipeline_stages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL,
    started_at TIMESTAMP,
    ended_at TIMESTAMP,
    duration_seconds BIGINT,
    pipeline_id BIGINT NOT NULL,
    CONSTRAINT fk_pipeline_stages_pipeline FOREIGN KEY (pipeline_id) REFERENCES pipelines (id)
);

CREATE TABLE deployments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL,
    docker_image VARCHAR(200),
    namespace VARCHAR(100),
    replicas INTEGER,
    project_id BIGINT NOT NULL,
    environment_id BIGINT NOT NULL,
    deployed_by_id BIGINT,
    deployed_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_deployments_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_deployments_environment FOREIGN KEY (environment_id) REFERENCES environments (id),
    CONSTRAINT fk_deployments_user FOREIGN KEY (deployed_by_id) REFERENCES users (id)
);

CREATE TABLE clusters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    provider VARCHAR(50) NOT NULL,
    endpoint VARCHAR(255) NOT NULL,
    status VARCHAR(30) NOT NULL
);

CREATE TABLE containers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    image VARCHAR(200) NOT NULL,
    status VARCHAR(30) NOT NULL,
    cpu_usage VARCHAR(20),
    memory_usage VARCHAR(20),
    port VARCHAR(30),
    project_id BIGINT NOT NULL,
    cluster_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_containers_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_containers_cluster FOREIGN KEY (cluster_id) REFERENCES clusters (id)
);

CREATE TABLE kubernetes_pods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    namespace VARCHAR(100) NOT NULL,
    status VARCHAR(30) NOT NULL,
    ready VARCHAR(20),
    restarts VARCHAR(20),
    node_name VARCHAR(100),
    project_id BIGINT NOT NULL,
    cluster_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_kubernetes_pods_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_kubernetes_pods_cluster FOREIGN KEY (cluster_id) REFERENCES clusters (id)
);

CREATE TABLE kubernetes_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    namespace VARCHAR(100) NOT NULL,
    type VARCHAR(30) NOT NULL,
    cluster_ip VARCHAR(45),
    port VARCHAR(100),
    cluster_id BIGINT,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_kubernetes_services_cluster FOREIGN KEY (cluster_id) REFERENCES clusters (id)
);

CREATE TABLE vulnerabilities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cve VARCHAR(100) NOT NULL,
    package_name VARCHAR(200) NOT NULL,
    severity VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    description VARCHAR(500),
    fixed_in_version VARCHAR(100),
    project_id BIGINT NOT NULL,
    discovered_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_vulnerabilities_project FOREIGN KEY (project_id) REFERENCES projects (id)
);

CREATE TABLE security_scans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    scan_type VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL,
    score INTEGER,
    project_id BIGINT NOT NULL,
    scanned_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_security_scans_project FOREIGN KEY (project_id) REFERENCES projects (id)
);

CREATE TABLE monitoring_metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metric_name VARCHAR(100) NOT NULL,
    metric_value DOUBLE PRECISION NOT NULL,
    unit VARCHAR(30),
    project_id BIGINT NOT NULL,
    environment_id BIGINT,
    captured_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_monitoring_metrics_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT fk_monitoring_metrics_environment FOREIGN KEY (environment_id) REFERENCES environments (id)
);

CREATE TABLE log_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(150) NOT NULL,
    level VARCHAR(30) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    project_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_log_events_project FOREIGN KEY (project_id) REFERENCES projects (id)
);

CREATE INDEX idx_refresh_sessions_user_id ON refresh_sessions (user_id);
CREATE INDEX idx_projects_owner_id ON projects (owner_id);
CREATE INDEX idx_pipelines_project_id ON pipelines (project_id);
CREATE INDEX idx_pipeline_stages_pipeline_id ON pipeline_stages (pipeline_id);
CREATE INDEX idx_deployments_project_id ON deployments (project_id);
CREATE INDEX idx_containers_project_id ON containers (project_id);
CREATE INDEX idx_kubernetes_pods_project_id ON kubernetes_pods (project_id);
CREATE INDEX idx_kubernetes_services_cluster_id ON kubernetes_services (cluster_id);
CREATE INDEX idx_vulnerabilities_project_id ON vulnerabilities (project_id);
CREATE INDEX idx_security_scans_project_id ON security_scans (project_id);
CREATE INDEX idx_monitoring_metrics_captured_at ON monitoring_metrics (captured_at);
CREATE INDEX idx_log_events_project_id ON log_events (project_id);
